// BlenderColor.cs - how Blender stores a glTF vertex colour: the importer hands linear floats to a BYTE_COLOR attribute,
// whose RNA setter (rna_ByteColorAttributeValue_color_set) converts RGB with linearrgb_to_srgb_v3_v3 and the alpha as is,
// each to a byte with unit_float_to_uchar_clamp (step 5 of replacing Blender, milestone c, 2026-10-03; read at Blender
// 5.1.2, blenlib/intern/math_color.cc and math_color_inline.cc).
// On x86-64 Blender takes the SSE2 path, linearrgb_to_srgb_v4_simd: pow(c, 1/2.4) is approximated through float/int bit
// casts (_bli_math_fastpow, rounding with cvtps2dq, i.e. to nearest even) and THREE reciprocal square roots, each the
// rsqrtps instruction plus one Newton step. rsqrtps is a 12-bit hardware approximation whose table differs between CPU
// vendors and generations, so the bytes are only reproducible for a CPU whose table is known: the table below was read
// off an AMD Ryzen 7 7800X3D (Zen 4, "Family 25 Model 97") with .NET 8's Sse.ReciprocalSqrtScalar - every input is
// determined by its exponent parity and top 12 mantissa bits (checked over all 2^24 mantissas of [1, 4)), and scaling the
// input by 4 halves the result exactly (2 million random inputs across all exponents: none off). On any other CPU,
// TableKnown is false and the reduce keeps Blender for a coloured mesh.
