    /// <summary>True when this machine's CPU is the one the rsqrtps table was read from.</summary>
    public static bool TableKnown
    {
        get
        {
            string id = Environment.GetEnvironmentVariable("PROCESSOR_IDENTIFIER") ?? "";
            return id.Contains("AuthenticAMD") && id.Contains("Family 25 Model 97");
        }
    }

    static uint[] table;

    static uint[] Table()
    {
        if (table != null) return table;
        var t = new uint[8192];
        for (int half = 0; half < 2; half++)
        {
            uint v = half == 0 ? RsqrtStart0 : RsqrtStart1; string steps = half == 0 ? RsqrtSteps0 : RsqrtSteps1;
            t[half * 4096] = v;
            for (int i = 1; i < 4096; i++) { v -= (uint)(steps[i - 1] - '0') << 11; t[half * 4096 + i] = v; }
        }
        return table = t;
    }

    static float AsFloat(uint u) => BitConverter.ToSingle(BitConverter.GetBytes(u), 0);
    static uint AsUint(float f) => BitConverter.ToUInt32(BitConverter.GetBytes(f), 0);
    static int AsInt(float f) => BitConverter.ToInt32(BitConverter.GetBytes(f), 0);
    static float IntAsFloat(int i) => BitConverter.ToSingle(BitConverter.GetBytes(i), 0);

    /// <summary>rsqrtps on the measured CPU: x = 4^k y with y in [1, 4) gives table(y) / 2^k; zero or a denormal gives +inf
    /// (the instruction treats a denormal as zero), a negative input NaN.</summary>
    public static float Rsqrtps(float x)
    {
        uint bits = AsUint(x);
        if ((bits & 0x80000000u) != 0 && x != 0f) return float.NaN;
        int e = (int)((bits >> 23) & 0xff);
        if (e == 0) return float.PositiveInfinity;
        if (e == 255) return float.IsNaN(x) ? x : 0f;
        int ex = e - 127, par = ex & 1, half = (ex - par) / 2;   // floor division: ex - par is even
        uint r = Table()[par * 4096 + (int)((bits >> 11) & 0xfff)];
        int re = (int)((r >> 23) & 0xff) - half;   // the table's results are normal and the scaling stays in range for our inputs
        if (re <= 0 || re >= 255) return (float)(AsFloat(r) * Math.Pow(2.0, -half));
        return AsFloat((r & 0x807fffffu) | ((uint)re << 23));
    }

    /// <summary>_bli_math_rsqrt: rsqrtps and one Newton step, 1.5 r + ((in * -0.5) * r) * (r * r).</summary>
    static float Rsqrt(float x)
    {
        float r = Rsqrtps(x);
        return (float)((float)(1.5f * r) + (float)((float)((float)(x * -0.5f) * r) * (float)(r * r)));
    }

    /// <summary>cvtps2dq: float to int32, round to nearest even; out of range (or NaN) gives int.MinValue.</summary>
    static int CvtRound(float f)
    {
        if (float.IsNaN(f) || f >= 2147483648f || f < -2147483648f) return int.MinValue;
        return (int)Math.Round((double)f, MidpointRounding.ToEven);
    }

    /// <summary>_bli_math_fastpow (SSE): arg * e2coeff, its bits read as an int and converted to float, times exp, converted
    /// back to an int (to nearest even) whose bits are the result.</summary>
    static float FastPow(uint exp, uint e2coeff, float arg)
    {
        float ret = (float)(arg * AsFloat(e2coeff));
        ret = (float)AsInt(ret);
        ret = (float)(ret * AsFloat(exp));
        return IntAsFloat(CvtRound(ret));
    }

    static readonly float Avg = (float)((float)(1.0f / (float)(3.0f * 0.629960524947437f)) * 0.999852f);

    /// <summary>_bli_math_fastpow512: pow(arg, 1 / 2.4).</summary>
    static float FastPow512(float arg)
    {
        float xf = FastPow(0x3f2aaaab, 0x5eb504f3, arg);
        float xover = (float)(arg * xf);
        float xfm1 = Rsqrt(xf);
        float x2 = (float)(arg * arg);
        float xunder = (float)(x2 * xfm1);
        float xavg = (float)(Avg * (float)(xover + xunder));
        xavg = (float)(xavg * Rsqrt(xavg));
        xavg = (float)(xavg * Rsqrt(xavg));
        return xavg;
    }

    /// <summary>linearrgb_to_srgb_v4_simd for one lane: below 0.0031308 max(c * 12.92, 0), else 1.055 pow512(c) - 0.055 (the
    /// pow lane is computed for every input, the blend picks).</summary>
    public static float LinearToSrgb(float c)
    {
        float lt = Math.Max((float)(c * 12.92f), 0.0f);
        if (c < 0.0031308f) return lt;
        return (float)((float)(1.055f * FastPow512(c)) + -0.055f);
    }

    /// <summary>unit_float_to_uchar_clamp.</summary>
    public static byte UnitToByte(float v)
    {
        if (v <= 0.0f) return 0;
        if (v > (float)(1.0f - (float)(0.5f / 255.0f))) return 255;
        return (byte)(float)((float)(255.0f * v) + 0.5f);
    }

