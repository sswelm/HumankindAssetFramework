    {
        into[at] = UnitToByte(LinearToSrgb(r)); into[at + 1] = UnitToByte(LinearToSrgb(g)); into[at + 2] = UnitToByte(LinearToSrgb(b)); into[at + 3] = UnitToByte(a);
    }

